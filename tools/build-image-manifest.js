#!/usr/bin/env node
/*  Scans the "dog headshots" folder and writes js/images.js, which maps each
 *  breed to its image filename. Run this after adding or renaming images:
 *
 *      node tools/build-image-manifest.js
 *
 *  Matching ignores case, spaces, punctuation and accents, so
 *  "Labrador Retriever.jpg", "labrador_retriever.png" and
 *  "Labrador-Retriever.JPG" all land on the same breed.
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const DIR = path.join(ROOT, 'dog headshots');
const OK_EXT = new Set(['.jpg', '.jpeg', '.png', '.webp', '.gif', '.avif']);

const src = fs.readFileSync(path.join(ROOT, 'js', 'breeds.js'), 'utf8');
const { BREEDS, breedSlug } = new Function(src + '; return { BREEDS, breedSlug };')();

const norm = s => s.normalize('NFD').replace(/[̀-ͯ]/g, '')
                   .toLowerCase().replace(/[^a-z0-9]/g, '');

const byNorm = new Map();
BREEDS.forEach(b => byNorm.set(norm(b.n), b));

if (!fs.existsSync(DIR)) { console.error('No "dog headshots" folder found.'); process.exit(1); }

const files = fs.readdirSync(DIR).filter(f => !f.startsWith('.') && !f.startsWith('_'));
const manifest = {};
const unmatched = [];
const collisions = [];

files.forEach(f => {
  const ext = path.extname(f).toLowerCase();
  if (!OK_EXT.has(ext)) { if (ext) unmatched.push(f + '  (not an image)'); return; }
  const breed = byNorm.get(norm(path.basename(f, path.extname(f))));
  if (!breed) { unmatched.push(f); return; }
  const slug = breedSlug(breed.n);
  if (manifest[slug]) { collisions.push(`${breed.n}: "${manifest[slug]}" and "${f}"`); return; }
  manifest[slug] = f;
});

const keys = Object.keys(manifest).sort();
const body = keys.map(k => `  ${JSON.stringify(k)}: ${JSON.stringify(manifest[k])}`).join(',\n');
fs.writeFileSync(path.join(ROOT, 'js', 'images.js'),
`// GENERATED by tools/build-image-manifest.js -- do not edit by hand.
// Breed slug -> filename inside the "dog headshots" folder.
// Re-run the script whenever you add or rename an image.
const BREED_IMAGES = {
${body}
};
`);

const have = keys.length, total = BREEDS.length;
console.log(`\nWrote js/images.js  --  ${have} of ${total} breeds have a headshot (${total - have} still to go)\n`);
if (collisions.length) {
  console.log('Two files matched the same breed (kept the first):');
  collisions.forEach(c => console.log('  ' + c));
  console.log('');
}
if (unmatched.length) {
  console.log("These files didn't match any breed name -- check the spelling against");
  console.log('"dog headshots/_FILENAMES.txt":');
  unmatched.forEach(u => console.log('  ' + u));
  console.log('');
}
